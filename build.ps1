# Builds NexShare APKs without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
# Toolchain lives in .tools and libraries in libs (see setup.ps1).
# Usage: .\build.ps1 [-Flavor normal|root|all]   -> dist\NexShare-vX.apk, dist\NexShare-Root-vX.apk
param([ValidateSet('normal', 'root', 'all')][string]$Flavor = 'all')
$ErrorActionPreference = 'Stop'
if ($Flavor -eq 'all') {
    & $PSCommandPath -Flavor normal
    & $PSCommandPath -Flavor root
    return
}
$Root = $PSScriptRoot
$Tools = Join-Path $Root '.tools'
$Jdk = Get-ChildItem (Join-Path $Tools 'jdk') -Directory | Select-Object -First 1
$env:JAVA_HOME = $Jdk.FullName
$env:Path = "$($Jdk.FullName)\bin;$env:Path"
$Sdk = Join-Path $Tools 'sdk'
$BT = Join-Path $Sdk 'build-tools\36.0.0' # 34's d8 crashes on libtorrent4j
$AndroidJar = Join-Path $Sdk 'platforms\android-34\android.jar'
$App = Join-Path $Root 'app'
$Out = Join-Path $Root "build\$Flavor"
$IsRootFlavor = $Flavor -eq 'root'
$LibJar = Join-Path $Root 'libs\libtorrent4j-2.1.0-39.jar'
$NativeJars = @{ 'arm64-v8a' = 'libs\libtorrent4j-android-arm64-2.1.0-39.jar'; 'armeabi-v7a' = 'libs\libtorrent4j-android-arm-2.1.0-39.jar' }
# cloudflared binaries, bundled as lib*.so so they land executable in nativeLibraryDir.
$Cloudflared = @{ 'arm64-v8a' = 'libs\cloudflared-linux-arm64'; 'armeabi-v7a' = 'libs\cloudflared-linux-arm' }

function Run($exe, [string[]]$argv) {
    $ErrorActionPreference = 'Continue' # tools write notes to stderr; rely on exit codes
    & $exe @argv 2>&1 | ForEach-Object { "$_" }
    if ($LASTEXITCODE -ne 0) { throw "$exe failed ($LASTEXITCODE)" }
}

if (Test-Path $Out) { Remove-Item $Out -Recurse -Force }
New-Item -ItemType Directory -Force "$Out\gen\com\nexshare", "$Out\classes", "$Out\dex" | Out-Null

Write-Host "== [$Flavor] manifest + flavor constants"
$utf8 = New-Object Text.UTF8Encoding $false
$manifest = [IO.File]::ReadAllText("$App\AndroidManifest.xml")
$version = [regex]::Match($manifest, 'android:versionName="([^"]+)"').Groups[1].Value
$appId = 'com.nexshare'
if ($IsRootFlavor) {
    # Separate package id so both editions can be installed side by side.
    $appId = 'com.nexshare.root'
    $manifest = $manifest.Replace('package="com.nexshare"', 'package="com.nexshare.root"').Replace('android:label="NexShare"', 'android:label="NexShare Root"')
}
# aapt2 doesn't expand manifest placeholders (a Gradle feature), so do it here.
$manifest = $manifest.Replace('${applicationId}', $appId)
[IO.File]::WriteAllText("$Out\AndroidManifest.xml", $manifest, $utf8)
$rootLiteral = if ($IsRootFlavor) { 'true' } else { 'false' }
[IO.File]::WriteAllText("$Out\gen\com\nexshare\Flavor.java", @"
package com.nexshare;

/** Generated by build.ps1. */
public final class Flavor {
    public static final boolean ROOT = $rootLiteral;
    public static final String VERSION = "$version";
}
"@, $utf8)

Write-Host '== aapt2 compile/link'
Run "$BT\aapt2.exe" @('compile', '--dir', "$App\res", '-o', "$Out\res.zip")
# Assets are added in the package step: aapt2 on Windows writes them with backslash paths.
Run "$BT\aapt2.exe" @('link', '-I', $AndroidJar, '--manifest', "$Out\AndroidManifest.xml",
    '--java', "$Out\gen", '--custom-package', 'com.nexshare', '--min-sdk-version', '24', '--target-sdk-version', '34',
    '-o', "$Out\base.apk", "$Out\res.zip")

Write-Host '== javac'
$sources = @(Get-ChildItem "$App\src", "$Out\gen" -Recurse -Filter *.java | ForEach-Object FullName)
Run 'javac' (@('-encoding', 'UTF-8', '-Xlint:-options', '-nowarn',
    '--release', '8', '-classpath', "$AndroidJar;$LibJar", '-d', "$Out\classes") + $sources)

Write-Host '== d8'
$classes = @(Get-ChildItem "$Out\classes" -Recurse -Filter *.class | ForEach-Object FullName)
Run "$BT\d8.bat" (@('--release', '--min-api', '24', '--lib', $AndroidJar, '--output', "$Out\dex") + $classes + @($LibJar))

Write-Host '== package'
Copy-Item "$Out\base.apk" "$Out\unaligned.apk"
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [System.IO.Compression.ZipFile]::Open("$Out\unaligned.apk", 'Update')
foreach ($dex in Get-ChildItem "$Out\dex" -Filter *.dex) {
    [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $dex.FullName, $dex.Name) | Out-Null
}
$assetsDir = (Resolve-Path "$App\assets").Path
foreach ($f in Get-ChildItem $assetsDir -Recurse -File) {
    $name = 'assets/' + $f.FullName.Substring($assetsDir.Length + 1).Replace('\', '/')
    [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $f.FullName, $name) | Out-Null
}
foreach ($abi in $NativeJars.Keys) {
    $src = [System.IO.Compression.ZipFile]::OpenRead((Join-Path $Root $NativeJars[$abi]))
    foreach ($e in $src.Entries | Where-Object { $_.FullName -like 'lib/*.so' }) {
        $dst = $zip.CreateEntry("lib/$abi/" + $e.Name)
        $rs = $e.Open(); $ws = $dst.Open(); $rs.CopyTo($ws); $ws.Dispose(); $rs.Dispose()
    }
    $src.Dispose()
}
foreach ($abi in $Cloudflared.Keys) {
    $bin = Join-Path $Root $Cloudflared[$abi]
    if (Test-Path $bin) {
        $dst = $zip.CreateEntry("lib/$abi/libcloudflared.so")
        $rs = [IO.File]::OpenRead($bin); $ws = $dst.Open(); $rs.CopyTo($ws); $ws.Dispose(); $rs.Dispose()
    }
}
$zip.Dispose()
Run "$BT\zipalign.exe" @('-v', '-p', '-f', '4', "$Out\unaligned.apk", "$Out\aligned.apk") | Out-Null

Write-Host '== sign'
$ks = Join-Path $Tools 'nexshare.keystore'
$passFile = Join-Path $Tools 'keystore.pass'
if (-not (Test-Path $ks)) {
    $pass = -join ((48..57) + (97..122) | Get-Random -Count 20 | ForEach-Object { [char]$_ })
    Set-Content -Path $passFile -Value $pass -NoNewline -Encoding ascii
    Run 'keytool' @('-genkeypair', '-keystore', $ks, '-alias', 'nexshare', '-keyalg', 'RSA', '-keysize', '2048',
        '-validity', '10000', '-storepass', $pass, '-keypass', $pass, '-dname', 'CN=NexShare')
}
$pass = Get-Content $passFile -Raw
New-Item -ItemType Directory -Force (Join-Path $Root 'dist') | Out-Null
$suffix = if ($IsRootFlavor) { 'Root-' } else { '' }
$apk = Join-Path $Root "dist\NexShare-${suffix}v$version.apk"
Run "$BT\apksigner.bat" @('sign', '--ks', $ks, '--ks-pass', "pass:$pass", '--out', $apk, "$Out\aligned.apk")
Run "$BT\apksigner.bat" @('verify', $apk)
Write-Host "== done: $apk ($([math]::Round((Get-Item $apk).Length / 1KB)) KB)"
