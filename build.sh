#!/usr/bin/env bash
# Linux/macOS counterpart of build.ps1. Builds NexShare APKs without Gradle:
# aapt2 -> javac -> d8 -> zip -> zipalign -> apksigner.
#
#   ./build.sh [normal|root|all]      -> dist/NexShare-vX.apk, dist/NexShare-Root-vX.apk
#
# Signing: uses $NEXSHARE_KEYSTORE / $NEXSHARE_KEYSTORE_PASS when set (CI), otherwise
# .tools/nexshare.keystore (created on first build, same as build.ps1). Keep using the same
# keystore across releases, or phones can't update the installed app.
set -euo pipefail
FLAVOR="${1:-all}"
ROOT="$(cd "$(dirname "$0")" && pwd)"
if [ "$FLAVOR" = all ]; then
  "$0" normal
  "$0" root
  exit 0
fi
case "$FLAVOR" in normal|root) ;; *) echo "usage: $0 [normal|root|all]"; exit 2 ;; esac

TOOLS="$ROOT/.tools"
SDK="${ANDROID_SDK_ROOT:-$(cat "$TOOLS/sdk.path" 2>/dev/null || echo "$TOOLS/sdk")}"
BT="$SDK/build-tools/36.0.0"
ANDROID_JAR="$SDK/platforms/android-34/android.jar"
APP="$ROOT/app"
OUT="$ROOT/build/$FLAVOR"
LT="$ROOT/libs/libtorrent4j-2.1.0-39.jar"
for f in "$BT/aapt2" "$BT/d8" "$ANDROID_JAR" "$LT"; do [ -e "$f" ] || { echo "missing $f — run ./setup.sh"; exit 1; }; done

rm -rf "$OUT" && mkdir -p "$OUT/gen/com/nexshare" "$OUT/classes" "$OUT/dex" "$OUT/pkg"

echo "== [$FLAVOR] manifest + flavor constants"
VERSION="$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' "$APP/AndroidManifest.xml")"
APP_ID=com.nexshare
MANIFEST="$(cat "$APP/AndroidManifest.xml")"
ROOT_LITERAL=false
if [ "$FLAVOR" = root ]; then
  # Separate package id so both editions can be installed side by side.
  APP_ID=com.nexshare.root
  ROOT_LITERAL=true
  MANIFEST="${MANIFEST/package=\"com.nexshare\"/package=\"com.nexshare.root\"}"
  MANIFEST="${MANIFEST/android:label=\"NexShare\"/android:label=\"NexShare Root\"}"
fi
# aapt2 doesn't expand manifest placeholders (a Gradle feature), so do it here.
MANIFEST="${MANIFEST//\$\{applicationId\}/$APP_ID}"
printf '%s\n' "$MANIFEST" > "$OUT/AndroidManifest.xml"
cat > "$OUT/gen/com/nexshare/Flavor.java" <<EOF
package com.nexshare;

/** Generated by build.sh. */
public final class Flavor {
    public static final boolean ROOT = $ROOT_LITERAL;
    public static final String VERSION = "$VERSION";
}
EOF

echo "== aapt2 compile/link"
"$BT/aapt2" compile --dir "$APP/res" -o "$OUT/res.zip"
"$BT/aapt2" link -I "$ANDROID_JAR" --manifest "$OUT/AndroidManifest.xml" \
  --java "$OUT/gen" --custom-package com.nexshare --min-sdk-version 24 --target-sdk-version 34 \
  -o "$OUT/base.apk" "$OUT/res.zip"

echo "== javac"
find "$APP/src" "$OUT/gen" -name '*.java' > "$OUT/sources.txt"
javac -encoding UTF-8 -Xlint:-options -nowarn --release 8 -classpath "$ANDROID_JAR:$LT" -d "$OUT/classes" @"$OUT/sources.txt"

echo "== d8"
find "$OUT/classes" -name '*.class' > "$OUT/classes.txt"
"$BT/d8" --release --min-api 24 --lib "$ANDROID_JAR" --output "$OUT/dex" @"$OUT/classes.txt" "$LT"

echo "== package"
cp "$OUT/base.apk" "$OUT/unaligned.apk"
PKG="$OUT/pkg"
cp "$OUT"/dex/*.dex "$PKG/"
mkdir -p "$PKG/assets" && cp -R "$APP/assets/." "$PKG/assets/"
for abi in arm64-v8a armeabi-v7a; do
  case $abi in arm64-v8a) suf=arm64 ;; *) suf=arm ;; esac
  mkdir -p "$PKG/lib/$abi"
  unzip -q -o -j "$ROOT/libs/libtorrent4j-android-$suf-2.1.0-39.jar" 'lib/*.so' -d "$PKG/lib/$abi"
  # cloudflared / busybox ship as lib*.so so Android extracts them executable into nativeLibraryDir.
  [ -f "$ROOT/libs/cloudflared-linux-$suf" ] && cp "$ROOT/libs/cloudflared-linux-$suf" "$PKG/lib/$abi/libcloudflared.so"
  if [ "$FLAVOR" = root ] && [ -f "$ROOT/libs/busybox-$suf" ]; then cp "$ROOT/libs/busybox-$suf" "$PKG/lib/$abi/libbusybox.so"; fi
done
(cd "$PKG" && zip -q -r -X "$OUT/unaligned.apk" .)
"$BT/zipalign" -p -f 4 "$OUT/unaligned.apk" "$OUT/aligned.apk"

echo "== sign"
KS="${NEXSHARE_KEYSTORE:-$TOOLS/nexshare.keystore}"
PASS="${NEXSHARE_KEYSTORE_PASS:-}"
if [ -z "$PASS" ]; then
  PASS_FILE="$TOOLS/keystore.pass"
  if [ ! -f "$KS" ]; then
    mkdir -p "$TOOLS"
    head -c 32 /dev/urandom | base64 | tr -dc 'a-z0-9' | head -c 20 > "$PASS_FILE"
    keytool -genkeypair -keystore "$KS" -alias nexshare -keyalg RSA -keysize 2048 -validity 10000 \
      -storepass "$(cat "$PASS_FILE")" -keypass "$(cat "$PASS_FILE")" -dname CN=NexShare
  fi
  PASS="$(cat "$PASS_FILE")"
fi
mkdir -p "$ROOT/dist"
SUFFIX=""
[ "$FLAVOR" = root ] && SUFFIX="Root-"
APK="$ROOT/dist/NexShare-${SUFFIX}v$VERSION.apk"
"$BT/apksigner" sign --ks "$KS" --ks-pass "pass:$PASS" --out "$APK" "$OUT/aligned.apk"
"$BT/apksigner" verify "$APK"
echo "== done: $APK ($(( $(wc -c < "$APK") / 1024 )) KB)"
